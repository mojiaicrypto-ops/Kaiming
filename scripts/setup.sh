#!/usr/bin/env bash
#
# Install the webapp/server dependencies, build the shell and create a local .env.
# Safe to run again: it refreshes dependencies and the build, but never overwrites an
# existing kaiming/.env (and therefore never changes the access password).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$ROOT/kaiming"

die() {
  printf 'setup: %s\n' "$1" >&2
  exit 1
}

command -v node >/dev/null 2>&1 || die 'Node.js is required. Install Node 24 LTS first.'
command -v npm >/dev/null 2>&1 || die 'npm is required. Install it with Node.js.'

node - <<'NODE'
const [major, minor, patch] = process.versions.node.split('.').map(Number);
if (major < 24) {
  console.error(`setup: Node 24+ is required; found ${process.versions.node}.`);
  process.exit(1);
}
if (major === 24 && (minor < 22 || (minor === 22 && patch < 1))) {
  console.warn(
    `setup: Node ${process.versions.node} can run the workbench, but one document parser ` +
      'declares Node 24.22.1+. Upgrade if npm prints an engine warning.',
  );
}
NODE

printf 'Installing server dependencies...\n'
if [ -f "$APP/package-lock.json" ]; then
  npm --prefix "$APP" ci
else
  npm --prefix "$APP" install
fi

printf 'Installing web dependencies...\n'
if [ -f "$APP/webapp/package-lock.json" ]; then
  npm --prefix "$APP/webapp" ci
else
  npm --prefix "$APP/webapp" install
fi

printf 'Building the browser shell...\n'
npm --prefix "$APP" run build

created_env=0
if [ ! -f "$APP/.env" ]; then
  umask 077
  password="$(node -e "process.stdout.write(require('node:crypto').randomBytes(18).toString('base64url'))")"
  {
    printf '# Generated by scripts/setup.sh. Keep this file private; it is gitignored.\n'
    printf 'KAIMING_ACCESS_PASSWORD=%s\n' "$password"
    printf 'KAIMING_HOST=127.0.0.1\n'
    printf 'KAIMING_PORT=4173\n'
    printf 'KAIMING_DATA_DIR=./.kaiming-data\n'
  } >"$APP/.env"
  chmod 600 "$APP/.env"
  created_env=1
fi

printf '\nKaiming is ready.\n\n'
printf 'Start:    ./scripts/start.sh\n'
printf 'Open:     http://127.0.0.1:4173\n'
if [ "$created_env" -eq 1 ]; then
  printf 'Password: %s\n' "$password"
  printf 'Saved in: kaiming/.env (mode 600)\n'
else
  printf 'Password: existing kaiming/.env kept unchanged\n'
  printf 'Read it with: grep KAIMING_ACCESS_PASSWORD kaiming/.env\n'
fi
printf '\nOptional browser tool: cd kaiming && npx playwright install chromium\n'
printf 'Full guide: docs/install.md\n'
