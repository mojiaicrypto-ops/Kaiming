/**
 * The Core side of `tool.execute`: request validation, the inline/deferred result
 * shapes and the endpoint's own refusal audit (`docs/architecture/protocol.md` §6).
 *
 * §6 lists the method and §7 fixes what a refusal looks like:
 *
 * > tool.execute* | attemptId,epoch,toolName,args,expectedInputHash? | accepted或工具结果Ref
 * > 错误表：… NOT_AUTHORIZED（有效Grant）… IDEMPOTENCY_CONFLICT … BUDGET_EXCEEDED …
 *
 * This module deliberately contains **no policy**: the caller has already been
 * authenticated from its Attempt capability (the same `authenticate` the other control
 * methods use), and the tool call itself is admitted by the Broker against a Grant. What
 * lives here is the wire contract and the two things an endpoint owns:
 *
 * 1. **Shape.** Unknown body fields, a missing/non-string tool name, a non-object `args`,
 *    a malformed `expectedInputHash` and an out-of-range `timeoutMs` are all
 *    `VALIDATION_ERROR` (`protocol.md` §1: "必填参数缺失、未知字段或枚举错误返回
 *    VALIDATION_ERROR"). `expectedInputHash` is also *recomputed* here, so a Runner that
 *    disagrees with Core about the canonical form of its arguments is refused with
 *    `IDEMPOTENCY_CONFLICT` instead of silently running a call the ledger cannot key.
 * 2. **Audit.** `execution.md` §4 and AC-048 require that a refused tool call is
 *    recorded, not merely answered: every refusal this layer produces appends a
 *    `tool.refused` event with the operation, targets and code — never the decoded
 *    arguments, so an audit row cannot leak a secret value (`AC-051`).
 *
 * ## The two documented result shapes (Q-T3-1)
 *
 * `protocol.md` §6 says the answer is "accepted或工具结果Ref". A Pi tool call is a
 * request/answer exchange, so an `accepted` that required a second read surface would
 * invent protocol the product does not specify. The answer is therefore the result
 * itself when it is small, and otherwise a **bounded preview plus the Ref** the ledger
 * already recorded:
 *
 * ```json
 * {"v":1,"status":"executed","mode":"host","operation":"edit",
 *  "toolOperationId":"…","inputHash":"…","grantId":"…",
 *  "result":{"written":1},"resultRef":null,"truncated":false,"durationMs":42}
 * ```
 *
 * A deferred answer keeps `result` (a preview string) and sets `resultRef`/`truncated`,
 * which is what the Runner turns into "the complete value is stored under resultRef …"
 * in the model's tool text (`apps/runner/src/tool-client.ts`).
 */
import { LIMITS, TOOL_EXECUTE_FIELDS, TOOL_RESULT_INLINE_BYTES } from '@agentdev/contracts';
import type { JsonObject, Role } from '@agentdev/contracts';
import type { ProjectStore } from '@agentdev/storage';
import { hashToolInput, TOOL_EVENTS, type ToolSuccess } from './broker.js';
import { statusForControlCode } from './control-http.js';
import { ProtocolError } from './errors.js';

/** The path this handler answers on; the control endpoint mounts it. */
export const TOOL_EXECUTE_PATH = '/control/tool.execute';

/**
 * The authenticated caller.
 *
 * Every field comes from the Attempt capability, never from the body: a Runner cannot
 * name its own Run, Attempt, epoch or role, which is why a `tool.execute` request has no
 * identity members at all (`control-http.ts` `ControlCaller`).
 */
export interface ToolExecuteCaller {
  readonly runId: string;
  readonly attemptId: string;
  readonly epoch: number;
  readonly role: Role;
}

/** One `tool.execute` request after shape validation. */
export interface ToolExecuteRequest {
  readonly toolName: string;
  readonly args: JsonObject;
  /** Generated by the endpoint when the caller omitted one; echoed in the answer. */
  readonly toolOperationId: string;
  readonly expectedInputHash?: string;
  /** The deadline the caller asked for, already bounded by the documented ceiling. */
  readonly timeoutMs: number;
}

/** What a plan/execute handler returns for one admitted call. */
export interface ToolExecuteHandler {
  /**
   * Runs one tool call and returns the Broker's own outcome.
   *
   * The handler is the daemon's (`apps/daemon/src/tool-handler.ts`): it plans the call
   * from the shared contract schemas, attaches the Core-implemented bodies and invokes
   * the Broker. A refusal is a `ProtocolError`, so the status and code come from one
   * mapping (`statusForControlCode`).
   */
  execute(input: {
    readonly caller: ToolExecuteCaller;
    readonly request: ToolExecuteRequest;
    /** Aborted when the Runner's socket closed, so the tool's process group is killed. */
    readonly signal?: AbortSignal | undefined;
  }): Promise<ToolSuccess>;
}

export interface ToolExecuteEndpointOptions {
  readonly store: ProjectStore;
  readonly handler: ToolExecuteHandler;
  /** The documented ceiling; `LIMITS.shellTimeoutSec.max` unless a test narrows it. */
  readonly timeoutCeilingMs?: number;
  readonly timeoutDefaultMs?: number;
  /** Generates the tool-operation id when the caller omitted one. */
  readonly newToolOperationId: () => string;
  readonly log?: (line: string) => void;
}

/** One answer: the HTTP status plus the protocol body. */
export interface ToolExecuteAnswer {
  readonly status: number;
  readonly body: unknown;
}

/** The documented default deadline and its ceiling (`ARCHITECTURE.md` §5). */
export const DEFAULT_TOOL_REQUEST_TIMEOUT_MS = LIMITS.shellTimeoutSec.default * 1000;
export const MAX_TOOL_REQUEST_TIMEOUT_MS = LIMITS.shellTimeoutSec.max * 1000;

function errorBody(code: string, message: string, details?: JsonObject): JsonObject {
  return { error: { code, message, ...(details === undefined ? {} : { details }) } };
}

/**
 * Validates the body of one `tool.execute`.
 *
 * The identity members (`attemptId`, `epoch`) are accepted and ignored: the control
 * endpoint already authenticated them, and refusing them would break the shared control
 * envelope. Every *other* unknown member is a `VALIDATION_ERROR`, because a mistyped
 * `toolname` would otherwise run the documented call without the argument the model
 * meant to send.
 */
export function parseToolExecuteBody(
  body: JsonObject,
  options: Pick<
    ToolExecuteEndpointOptions,
    'newToolOperationId' | 'timeoutCeilingMs' | 'timeoutDefaultMs'
  >,
): ToolExecuteRequest {
  const unknown = Object.keys(body).filter((key) => !TOOL_EXECUTE_FIELDS.includes(key));
  if (unknown.length > 0) {
    throw new ProtocolError('VALIDATION_ERROR', `unknown fields: ${unknown.join(', ')}`, {
      details: { unknown },
    });
  }
  const toolName = body['toolName'];
  if (typeof toolName !== 'string' || toolName.length === 0) {
    throw new ProtocolError('VALIDATION_ERROR', 'toolName must be a non-empty string');
  }
  const args = body['args'];
  if (typeof args !== 'object' || args === null || Array.isArray(args)) {
    throw new ProtocolError('VALIDATION_ERROR', 'args must be an object');
  }
  const rawOperationId = body['toolOperationId'];
  if (rawOperationId !== undefined && typeof rawOperationId !== 'string') {
    throw new ProtocolError('VALIDATION_ERROR', 'toolOperationId must be a string');
  }
  const expected = body['expectedInputHash'];
  if (expected !== undefined) {
    if (typeof expected !== 'string' || !/^[0-9a-f]{64}$/.test(expected)) {
      throw new ProtocolError(
        'VALIDATION_ERROR',
        'expectedInputHash must be a lowercase SHA256 hex digest',
      );
    }
  }
  const ceiling = options.timeoutCeilingMs ?? MAX_TOOL_REQUEST_TIMEOUT_MS;
  const fallback = options.timeoutDefaultMs ?? DEFAULT_TOOL_REQUEST_TIMEOUT_MS;
  const rawTimeout = body['timeoutMs'];
  if (
    rawTimeout !== undefined &&
    (typeof rawTimeout !== 'number' || !Number.isInteger(rawTimeout))
  ) {
    throw new ProtocolError('VALIDATION_ERROR', 'timeoutMs must be an integer');
  }
  const timeoutMs = rawTimeout === undefined ? fallback : rawTimeout;
  if (timeoutMs <= 0 || timeoutMs > ceiling) {
    throw new ProtocolError(
      'VALIDATION_ERROR',
      `timeoutMs must be between 1 and ${String(ceiling)}; a Grant may raise the default ${String(fallback)} up to that ceiling`,
      { details: { timeoutMs, ceiling } },
    );
  }
  return {
    toolName,
    args,
    toolOperationId:
      rawOperationId === undefined || rawOperationId === ''
        ? options.newToolOperationId()
        : rawOperationId,
    ...(expected === undefined ? {} : { expectedInputHash: expected }),
    timeoutMs,
  };
}

/**
 * Renders a Broker success as the documented `tool.execute` answer (Q-T3-1).
 *
 * The inline ceiling is a byte count of the serialised result; a larger value is
 * replaced by a bounded preview while `resultRef` names the value the ledger recorded
 * (`ProjectStoreDeferredResultStore`, `reliability.md` §2). The full value is never lost:
 * it is already durable, which is what makes a replay return the original result.
 */
export function toolExecuteBody(success: ToolSuccess, durationMs: number): Record<string, unknown> {
  const serialized = JSON.stringify(success.result);
  const bytes = Buffer.byteLength(serialized ?? 'null', 'utf8');
  const ledger = success.ledger === undefined ? {} : { ledger: { ...success.ledger } };
  if (bytes <= TOOL_RESULT_INLINE_BYTES) {
    return {
      ...ledger,
      v: 1,
      status: success.outcome,
      mode: success.mode,
      operation: success.operation,
      toolName: success.toolOperation.toolName,
      toolOperationId: success.toolOperation.id,
      inputHash: success.inputHash,
      grantId: success.grantId,
      result: success.result ?? null,
      resultRef: null,
      truncated: false,
      durationMs,
    };
  }
  const preview = (serialized ?? 'null').slice(0, TOOL_RESULT_INLINE_BYTES);
  return {
    ...ledger,
    v: 1,
    status: success.outcome,
    mode: success.mode,
    operation: success.operation,
    toolName: success.toolOperation.toolName,
    toolOperationId: success.toolOperation.id,
    inputHash: success.inputHash,
    grantId: success.grantId,
    result: preview,
    resultRef: success.toolOperation.resultRef ?? null,
    truncated: true,
    durationMs,
  };
}

/**
 * Handles one `tool.execute` request.
 *
 * The caller is already authenticated; this function validates the shape, checks the
 * caller's own hash, asks the handler to run the call, and answers either the documented
 * result body or the protocol error envelope. Every refusal it produces is audited as
 * `tool.refused` with the operation, targets and code — a refused tool call must be
 * visible in the ledger even when no Grant was ever consulted (`execution.md` §4).
 */
export async function handleToolExecute(
  options: ToolExecuteEndpointOptions,
  caller: ToolExecuteCaller,
  body: JsonObject,
  signal?: AbortSignal,
): Promise<ToolExecuteAnswer> {
  const log = options.log ?? ((): void => undefined);
  let operationId = typeof body['toolOperationId'] === 'string' ? body['toolOperationId'] : '';
  /** The body's tool name as text; a non-string member is the empty string, never "[object Object]". */
  const toolNameOf = (value: unknown): string => (typeof value === 'string' ? value : '');
  const audit = (
    code: string,
    message: string,
    toolName: string,
    operation: string,
    targets: readonly string[],
  ): void => {
    options.store.events.append({
      name: TOOL_EVENTS.refused,
      entityId: operationId === '' ? options.newToolOperationId() : operationId,
      entityVersion: 1,
      data: {
        workId: '',
        runId: caller.runId,
        operation,
        code,
        reason: message,
        targets: [...targets],
        mode: 'host',
        layer: 'endpoint',
      },
    });
  };
  try {
    const request = parseToolExecuteBody(body, options);
    operationId = request.toolOperationId;
    if (request.expectedInputHash !== undefined) {
      const computed = hashToolInput(request.args);
      if (computed !== request.expectedInputHash) {
        throw new ProtocolError(
          'IDEMPOTENCY_CONFLICT',
          `expectedInputHash ${request.expectedInputHash} does not match the canonical hash of args (${computed})`,
          { details: { toolOperationId: request.toolOperationId } },
        );
      }
    }
    const startedAt = Date.now();
    const success = await options.handler.execute({
      caller,
      request,
      ...(signal === undefined ? {} : { signal }),
    });
    log(
      `tool-endpoint: ${caller.runId} attempt ${caller.attemptId} ${request.toolName} ${success.outcome}`,
    );
    return { status: 200, body: toolExecuteBody(success, Date.now() - startedAt) };
  } catch (error) {
    if (error instanceof ProtocolError) {
      audit(
        error.code,
        error.message,
        toolNameOf(body['toolName']),
        toolNameOf(body['toolName']),
        [],
      );
      log(`tool-endpoint: refused ${error.code}: ${error.message}`);
      return {
        status: statusForControlCode(error.code),
        body: errorBody(error.code, error.message),
      };
    }
    const message = error instanceof Error ? error.message : String(error);
    log(`tool-endpoint: ${message}`);
    audit(
      'INTERNAL_ERROR',
      message,
      toolNameOf(body['toolName']),
      toolNameOf(body['toolName']),
      [],
    );
    return {
      status: 500,
      body: errorBody('INTERNAL_ERROR', 'the tool endpoint failed'),
    };
  }
}
