/**
 * `gui` (host-owned): fixed, read-only native macOS screenshots.
 *
 * Why a tool instead of `screencapture` in tester bash: the P3-1 sandbox deliberately has no access
 * to the user's home or the system temporary root, and macOS Screen Recording (TCC) is not granted
 * to the sandboxed child. The host owns a small signed helper app which holds that permission and
 * exposes only fixed capture arguments; the tester's sandbox is never widened.
 *
 * The helper is not a shell and this tool never launches a browser or an application. Web pages use
 * `browser`; an Electron window should use its own `capturePage` where possible. `gui` exists for
 * the pixels neither of those can produce (tray/status item, menu bar, desktop/window evidence).
 *
 * Deliberate limits:
 *  - macOS only; other platforms return UNSUPPORTED_PLATFORM;
 *  - target is one of screen/region/window; no mouse, keyboard or application launching;
 *  - numbers are validated and bounded; output paths are generated by the host, never supplied by
 *    the model;
 *  - a TCC denial is reported as a real error, never replaced by a fabricated screenshot.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { asRecord, fail, messageOf, ok, readNumber, readString, type ToolOutcome } from './tool-kit.ts';
import type { DomainTool } from './task-tools.ts';
import { storeImage } from '../server/attachments.ts';

const TARGETS = ['screen', 'region', 'window'] as const;
type GuiTarget = (typeof TARGETS)[number];

const CAPTURE_TIMEOUT_MS = 15_000;
const MAX_COORDINATE = 100_000;
const MAX_DIMENSION = 100_000;
const MAX_WINDOW_ID = 2_147_483_647;
const MAX_DISPLAY_INDEX = 31;
const HELPER_ENV = 'KAIMING_GUI_HELPER';
const DEFAULT_HELPER = resolve(fileURLToPath(new URL('../../native/GuiCapture.app', import.meta.url)));

export interface GuiCaptureParams {
  readonly target: GuiTarget;
  readonly display?: number;
  readonly windowId?: number;
  readonly x?: number;
  readonly y?: number;
  readonly width?: number;
  readonly height?: number;
}

export type GuiParamsResult =
  | { readonly ok: true; readonly params: GuiCaptureParams }
  | { readonly ok: false; readonly message: string };

export interface GuiCaptureRequest extends GuiCaptureParams {
  readonly outPath: string;
}

export interface GuiRunResult {
  readonly ok: boolean;
  readonly code?: string;
  readonly message?: string;
}

export interface GuiToolOptions {
  /** Attachment store root for the successful PNG. */
  readonly agentDir: string;
  /** Host-only override for a differently signed helper (operator configuration, not model input). */
  readonly helperPath?: string;
  /** The one seam tests replace instead of launching a real GUI helper. */
  readonly launcher?: (request: GuiCaptureRequest, helperPath: string) => GuiRunResult;
  readonly platform?: NodeJS.Platform;
}

export interface GuiHelperStatus {
  readonly ok: boolean;
  readonly code?: string;
  readonly message?: string;
}

function isTarget(value: string): value is GuiTarget {
  return (TARGETS as readonly string[]).includes(value);
}

function boundedInteger(
  record: Record<string, unknown>,
  key: string,
  minimum: number,
  maximum: number,
): number | undefined {
  const value = readNumber(record, key);
  if (value === undefined || !Number.isInteger(value) || value < minimum || value > maximum) {
    return undefined;
  }
  return value;
}

function hasKey(record: Record<string, unknown>, key: string): boolean {
  return Object.prototype.hasOwnProperty.call(record, key);
}

/**
 * Parse and validate exactly the fields the helper accepts. Cross-target fields are rejected rather
 * than ignored, so a screen capture cannot silently carry a window id or region.
 */
export function parseGuiParams(rawParams: unknown): GuiParamsResult {
  const params = asRecord(rawParams);
  if (params === undefined) {
    return { ok: false, message: 'params must be an object' };
  }
  const unknownKeys = Object.keys(params).filter(
    (key) => !['target', 'display', 'windowId', 'x', 'y', 'width', 'height'].includes(key),
  );
  if (unknownKeys.length > 0) {
    return { ok: false, message: `unknown argument(s): ${unknownKeys.join(', ')}` };
  }
  const target = readString(params, 'target');
  if (target === undefined || !isTarget(target)) {
    return { ok: false, message: `target must be one of ${TARGETS.join(', ')}` };
  }

  if (target === 'screen') {
    if (hasKey(params, 'windowId') || hasKey(params, 'x') || hasKey(params, 'y') || hasKey(params, 'width') || hasKey(params, 'height')) {
      return { ok: false, message: 'screen accepts only the optional display field' };
    }
    if (!hasKey(params, 'display')) {
      return { ok: true, params: { target } };
    }
    const display = boundedInteger(params, 'display', 0, MAX_DISPLAY_INDEX);
    if (display === undefined) {
      return { ok: false, message: `display must be an integer between 0 and ${MAX_DISPLAY_INDEX}` };
    }
    return { ok: true, params: { target, display } };
  }

  if (target === 'window') {
    if (hasKey(params, 'display') || hasKey(params, 'x') || hasKey(params, 'y') || hasKey(params, 'width') || hasKey(params, 'height')) {
      return { ok: false, message: 'window accepts only windowId' };
    }
    const windowId = boundedInteger(params, 'windowId', 1, MAX_WINDOW_ID);
    if (windowId === undefined) {
      return { ok: false, message: `windowId must be an integer between 1 and ${MAX_WINDOW_ID}` };
    }
    return { ok: true, params: { target, windowId } };
  }

  if (hasKey(params, 'display') || hasKey(params, 'windowId')) {
    return { ok: false, message: 'region accepts only x, y, width and height' };
  }
  const x = boundedInteger(params, 'x', -MAX_COORDINATE, MAX_COORDINATE);
  const y = boundedInteger(params, 'y', -MAX_COORDINATE, MAX_COORDINATE);
  const width = boundedInteger(params, 'width', 1, MAX_DIMENSION);
  const height = boundedInteger(params, 'height', 1, MAX_DIMENSION);
  if (x === undefined || y === undefined || width === undefined || height === undefined) {
    return {
      ok: false,
      message: `region needs integer x/y in -${MAX_COORDINATE}..${MAX_COORDINATE} and width/height in 1..${MAX_DIMENSION}`,
    };
  }
  return { ok: true, params: { target, x, y, width, height } };
}

/** The exact argv the helper receives. Output and status paths are host-generated. */
export function helperArguments(params: GuiCaptureParams, outPath: string, statusPath: string): string[] {
  const args = ['--out', outPath, '--status', statusPath, '--target', params.target];
  if (params.display !== undefined) args.push('--display', String(params.display));
  if (params.windowId !== undefined) args.push('--window-id', String(params.windowId));
  if (params.x !== undefined) args.push('--x', String(params.x));
  if (params.y !== undefined) args.push('--y', String(params.y));
  if (params.width !== undefined) args.push('--width', String(params.width));
  if (params.height !== undefined) args.push('--height', String(params.height));
  return args;
}

/** Read a helper status file; malformed status is a failure, not a success by absence. */
function readStatus(path: string): GuiHelperStatus | undefined {
  try {
    const parsed = JSON.parse(readFileSync(path, 'utf8')) as unknown;
    const record = asRecord(parsed);
    if (record === undefined || typeof record['ok'] !== 'boolean') {
      return undefined;
    }
    return {
      ok: record['ok'],
      ...(typeof record['code'] === 'string' ? { code: record['code'] } : {}),
      ...(typeof record['message'] === 'string' ? { message: record['message'] } : {}),
    };
  } catch {
    return undefined;
  }
}

function resolveHelperPath(options: GuiToolOptions): string {
  return options.helperPath ?? process.env[HELPER_ENV] ?? DEFAULT_HELPER;
}

/**
 * Launch the signed helper through LaunchServices, not as a direct child of the workbench. The
 * helper has its own TCC responsibility; the tester's sandbox is not involved.
 */
function runHelper(request: GuiCaptureRequest, helperPath: string): GuiRunResult {
  if (!existsSync(helperPath)) {
    return {
      ok: false,
      code: 'HELPER_UNAVAILABLE',
      message: `GuiCapture.app was not found at ${helperPath}. Build it with "bash kaiming/native/build.sh" and grant it Screen Recording permission.`,
    };
  }
  const statusPath = `${request.outPath}.status.json`;
  const args = helperArguments(request, request.outPath, statusPath);
  const child = spawnSync('/usr/bin/open', ['-W', '-n', '-a', helperPath, '--args', ...args], {
    encoding: 'utf8',
    timeout: CAPTURE_TIMEOUT_MS,
    maxBuffer: 1024 * 1024,
  });
  if (child.error !== undefined && child.error !== null) {
    return {
      ok: false,
      code: 'HELPER_LAUNCH_FAILED',
      message: `GuiCapture.app could not be launched: ${messageOf(child.error)}`,
    };
  }
  const status = readStatus(statusPath);
  if (status === undefined) {
    return {
      ok: false,
      code: 'HELPER_LAUNCH_FAILED',
      message: `GuiCapture.app did not write a status file${child.status === 0 ? '' : ` (open exit ${String(child.status)})`}. Check that the helper is signed and launchable.`,
    };
  }
  return status.ok
    ? { ok: true }
    : {
        ok: false,
        ...(status.code !== undefined ? { code: status.code } : {}),
        ...(status.message !== undefined ? { message: status.message } : {}),
      };
}

function tccMessage(message: string | undefined): string {
  return [
    message ?? 'macOS denied Screen Recording to the GUI helper.',
    'Grant Screen Recording to Kaiming GUI Capture in System Settings → Privacy & Security → Screen Recording, then retry. The tester bash sandbox cannot grant this permission.',
  ].join(' ');
}

export function createGuiTool(options: GuiToolOptions): DomainTool {
  return {
    name: 'gui',
    label: 'gui',
    description: [
      'Capture native macOS pixels (read-only) and store them as an attachment: target screen, a screen region, or a specific window.',
      'Use browser for web pages; prefer an app-internal capturePage for its own window. Use gui when the evidence is the status item, menu bar, desktop or another native window.',
      'This tool cannot click, type, launch applications or choose an output path. If macOS Screen Recording is not granted to the helper, it returns TCC_DENIED and does not fabricate an image.',
    ].join('\n'),
    parameters: {
      type: 'object',
      properties: {
        target: { type: 'string', enum: [...TARGETS], description: 'what to capture' },
        display: { type: 'integer', minimum: 0, maximum: MAX_DISPLAY_INDEX, description: 'for screen: display index (main display by default)' },
        windowId: { type: 'integer', minimum: 1, maximum: MAX_WINDOW_ID, description: 'for window: the CoreGraphics window id' },
        x: { type: 'integer', minimum: -MAX_COORDINATE, maximum: MAX_COORDINATE, description: 'for region: left edge in screen coordinates' },
        y: { type: 'integer', minimum: -MAX_COORDINATE, maximum: MAX_COORDINATE, description: 'for region: top edge in screen coordinates' },
        width: { type: 'integer', minimum: 1, maximum: MAX_DIMENSION, description: 'for region: width in screen points' },
        height: { type: 'integer', minimum: 1, maximum: MAX_DIMENSION, description: 'for region: height in screen points' },
      },
      required: ['target'],
      additionalProperties: false,
    },
    async execute(_toolCallId, rawParams): Promise<ToolOutcome> {
      if ((options.platform ?? process.platform) !== 'darwin') {
        return fail('UNSUPPORTED_PLATFORM', 'gui capture is implemented for macOS only; use browser for web evidence on this host.');
      }
      const parsed = parseGuiParams(rawParams);
      if (!parsed.ok) {
        return fail('INVALID_ARGUMENT', parsed.message);
      }
      const helperPath = resolveHelperPath(options);
      const dir = mkdtempSync(join(tmpdir(), 'kaiming-gui-'));
      const outPath = join(dir, 'capture.png');
      try {
        const request: GuiCaptureRequest = { ...parsed.params, outPath };
        const result = options.launcher !== undefined
          ? options.launcher(request, helperPath)
          : runHelper(request, helperPath);
        if (!result.ok) {
          const code = result.code ?? 'CAPTURE_FAILED';
          if (code === 'TCC_DENIED') {
            return fail('TCC_DENIED', tccMessage(result.message), {
              target: parsed.params.target,
              helper: helperPath,
              permission: 'screen-recording',
            });
          }
          return fail(code, result.message ?? 'native capture failed', {
            target: parsed.params.target,
            helper: helperPath,
          });
        }
        if (!existsSync(outPath)) {
          return fail('CAPTURE_FAILED', 'the GUI helper reported success but wrote no image', {
            target: parsed.params.target,
          });
        }
        const bytes = readFileSync(outPath);
        const stored = storeImage(options.agentDir, bytes);
        if (!stored.ok) {
          return fail('STORAGE_UNAVAILABLE', `the screenshot could not be stored: ${stored.message}`, {
            target: parsed.params.target,
          });
        }
        const details = {
          target: parsed.params.target,
          attachmentId: stored.image.id,
          bytes: bytes.byteLength,
          ...(parsed.params.windowId !== undefined ? { windowId: parsed.params.windowId } : {}),
          ...(parsed.params.display !== undefined ? { display: parsed.params.display } : {}),
          ...(parsed.params.x !== undefined
            ? { x: parsed.params.x, y: parsed.params.y, width: parsed.params.width, height: parsed.params.height }
            : {}),
        };
        const facts = `gui ${parsed.params.target} screenshot ${stored.image.id} (${String(bytes.byteLength)} bytes)`;
        return ok(facts, details, [
          { data: bytes.toString('base64'), mimeType: stored.image.mimeType },
        ]);
      } finally {
        rmSync(dir, { recursive: true, force: true });
      }
    },
  };
}

