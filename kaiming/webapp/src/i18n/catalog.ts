export const CATALOG: Record<Locale, Record<MessageKey, string>> = {
  en,
  'zh-CN': zhCN,
};

export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

/**
 * Build-time guard: both languages must describe exactly the same keys. Returns the symmetric
 * difference so a test can fail with the precise list instead of a rendering surprise.
 */
export function checkCatalog(): { missing: string[]; extra: string[] } {
  const enKeys = new Set(Object.keys(CATALOG.en));
  const zhKeys = new Set(Object.keys(CATALOG['zh-CN']));
  return {
    missing: [...enKeys].filter((key) => !zhKeys.has(key)),
    extra: [...zhKeys].filter((key) => !enKeys.has(key)),
  };
}

/** Substitute `{name}` placeholders; an unknown name is left visible rather than blank. */
export function format(template: string, values?: Record<string, string | number>): string {
  if (values === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole,
  );
}
